#!/usr/bin/env python3
"""Writes book/<slug>/index.html for every row in links.json: a no-design forwarder to the booking calendar
with the source tags on it. No pixel, nothing visible: it only adds the tags and hands off. Run: python3 book/_src/build.py"""
import json, html, pathlib
here = pathlib.Path(__file__).resolve().parent
cfg = json.loads((here / 'links.json').read_text())
CAL = cfg['calendar']
PAGE = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Book your call | LEADFUSE</title>
<meta name="robots" content="noindex"><meta name="viewport" content="width=device-width,initial-scale=1">
<!-- leadfuse.co/book/{slug}: {where}. Generated by book/_src/build.py from links.json, do not edit by hand. -->
<script>
(function () {{
  var tags = {tags};
  var u = new URL({cal});
  Object.keys(tags).forEach(function (k) {{ u.searchParams.set(k, tags[k]); }});
  // Anything on the clicked link (?utm_content=..., ?test=1) wins.
  new URLSearchParams(location.search).forEach(function (v, k) {{ if (v) u.searchParams.set(k, v); }});
  location.replace(u.toString());
}})();
</script>
<noscript><meta http-equiv="refresh" content="0;url={fallback}"></noscript>
<style>body{{margin:0;background:#000;color:#fff;font:16px/1.5 Poppins,-apple-system,system-ui,sans-serif;display:flex;min-height:100vh;align-items:center;justify-content:center}}a{{color:#fff}}</style>
</head><body><p>Opening the calendar… <a href="{fallback}">Open it</a></p></body></html>
"""
for row in cfg['links']:
    tags = {'formsource': row['formsource'], 'utm_source': row['utm_source'], 'utm_medium': row['utm_medium'], 'utm_campaign': 'book'}
    from urllib.parse import urlencode
    fallback = html.escape(CAL + '?' + urlencode(tags))
    out = here.parent / row['slug'] / 'index.html'
    out.parent.mkdir(exist_ok=True)
    out.write_text(PAGE.format(slug=row['slug'], where=html.escape(row['where']), tags=json.dumps(tags), cal=json.dumps(CAL), fallback=fallback))
    print('wrote', out.relative_to(here.parent.parent), tags)
