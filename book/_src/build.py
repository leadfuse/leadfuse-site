"""Builds leadfuse.co/book/<slug>/index.html from links.json.

Each one forwards to the application (leadfuse.co/apply/<apply>/), keeping the query.
Nobody is ever sent straight to a calendar: the application grades them first.
"""
import json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
data = json.loads((ROOT / '_src' / 'links.json').read_text())
PAGE = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>See if you qualify | LEADFUSE</title>
<meta name="robots" content="noindex"><meta name="viewport" content="width=device-width,initial-scale=1">
<!-- leadfuse.co/book/{slug}: {where}. Forwards to the application, never a calendar. Generated by book/_src/build.py from links.json, do not edit by hand. -->
<script>location.replace("/apply/{apply}/" + location.search + location.hash);</script>
<noscript><meta http-equiv="refresh" content="0;url=/apply/{apply}/"></noscript>
<style>body{{margin:0;background:#000;color:#fff;font:16px/1.5 Poppins,-apple-system,system-ui,sans-serif;display:flex;min-height:100vh;align-items:center;justify-content:center}}a{{color:#fff}}</style>
</head><body><p><a href="/apply/{apply}/">See if you qualify</a></p></body></html>
"""
for link in data['links']:
    out = ROOT / link['slug'] / 'index.html'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(PAGE.format(**link))
    print('built', out.relative_to(ROOT.parent))
