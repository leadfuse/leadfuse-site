#!/usr/bin/env python3
"""Writes /apply/index.html and one /apply/<slug>/index.html per source in sources.json from template.html.
Every page is the full application form and nothing else; only the hidden fields handed to the form differ.
Run from anywhere: python3 apply/_src/build.py"""
import json, pathlib, html
HERE = pathlib.Path(__file__).resolve().parent
APPLY = HERE.parent
cfg = json.loads((HERE / "sources.json").read_text())
tpl = (HERE / "template.html").read_text().replace("{{FORM}}", cfg["form"])
BANNER = "<!-- Generated by apply/_src/build.py from apply/_src/template.html. Edit the template, not this file. -->\n"

def hidden(src):
    return [("formsource", src["slug"]), ("utm_source", src["utm_source"]), ("utm_medium", src["medium"]), ("utm_campaign", "apply")]

def render(src):
    pairs = hidden(src)
    page = tpl.replace("{{HIDDEN}}", ",".join(f"{k}={v}" for k, v in pairs))
    page = page.replace("{{HASH}}", html.escape("&".join(f"{k}={v}" for k, v in pairs)))
    return page.replace("<!doctype html>\n", "<!doctype html>\n" + BANNER, 1)

written = []
(APPLY / "index.html").write_text(render(cfg["root"])); written.append("apply/index.html")
for src in cfg["sources"]:
    d = APPLY / src["slug"]; d.mkdir(exist_ok=True)
    (d / "index.html").write_text(render(src)); written.append(f"apply/{src['slug']}/index.html")
ALIAS = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Apply | LEADFUSE</title><meta name="robots" content="noindex">
<meta name="viewport" content="width=device-width,initial-scale=1"><!-- Generated by apply/_src/build.py: old link kept alive, forwards to /apply/__TO__/ -->
<script>location.replace('/apply/__TO__/' + location.search + location.hash);</script>
<style>body{margin:0;background:#000}</style></head><body><noscript><a href="/apply/__TO__/">Continue</a></noscript></body></html>
"""
for old_slug, new_slug in cfg.get("aliases", {}).items():
    d = APPLY / old_slug; d.mkdir(exist_ok=True)
    (d / "index.html").write_text(ALIAS.replace("__TO__", new_slug)); written.append(f"apply/{old_slug}/index.html -> {new_slug}")
print("\n".join(written))
